#!/usr/bin/env bash
# Vendors the platform-repo service charts into charts/platform-<svc>/ at a pinned
# release tag, so they publish through the same chart-releaser flow as every other
# chart and customers never need access to the platform repo.
#
#   scripts/sync-platform-charts.sh v2026.11.3 [--platform-repo PATH] [svc ...]
#
# Per chart: copies services/<svc>/deploy/helm/<svc> from the tag (git archive; the
# platform working tree is not touched), drops values/ (Straiker's per-environment
# SaaS values: account IDs, hosts, DSNs — never shipped), renames the chart to
# platform-<svc> and sets version/appVersion from the tag. Release names stay <svc>
# (resource names derive from the release name). charts/platform-<svc>/values-onprem.yaml
# is hand-maintained and never overwritten. Also rewrites the matching imageMirror tags in
# charts/straiker-artifact/values.yaml (not tracked by charts/image-tags.yaml).
#
# Also extracts the ClickHouse CDC replica target DDL (the CREATE TABLE statements of grid's
# harness fixture deploy/harness/seed/cdc_snapshot.sql, comments and seed rows dropped) into
# charts/straiker-ch-sync/files/cdc_targets.sql, run with the 'ch-sync' chart.
#
# Chart version: tag vYYYY.M.D[.N] -> YYYY.M.(D*100+N), monotonic for chart-releaser
# (v2026.11.3 -> 2026.11.300, v2026.11.1.2 -> 2026.11.102). appVersion = the tag.
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PLATFORM_REPO="${PLATFORM_REPO:-${HOME}/Desktop/Git_Repo/platform}"
DEFAULT_SERVICES=(foundation registry databridge grid portico connect)

tag=""; services=()
while [[ $# -gt 0 ]]; do
  case "$1" in
    --platform-repo) PLATFORM_REPO="$2"; shift 2 ;;
    -h|--help) sed -n '2,17p' "$0"; exit 0 ;;
    v*) tag="$1"; shift ;;
    *) services+=("$1"); shift ;;
  esac
done
[[ -n "${tag}" ]] || { echo "usage: $0 vYYYY.M.D[.N] [--platform-repo PATH] [svc ...]" >&2; exit 1; }
[[ ${#services[@]} -gt 0 ]] || services=("${DEFAULT_SERVICES[@]}")
git -C "${PLATFORM_REPO}" rev-parse --verify --quiet "refs/tags/${tag}^{commit}" >/dev/null \
  || { echo "tag ${tag} not found in ${PLATFORM_REPO}" >&2; exit 1; }

chart_version="$(python3 - "${tag}" <<'PY'
import re, sys
m = re.fullmatch(r"v(\d{4})\.(\d+)\.(\d+)(?:\.(\d+))?", sys.argv[1])
if not m: sys.exit("tag must look like vYYYY.M.D[.N]")
y, mo, d, n = m.groups()
print(f"{y}.{mo}.{int(d) * 100 + int(n or 0)}")
PY
)"

for svc in "${services[@]}"; do
  src="services/${svc}/deploy/helm/${svc}"
  dest="${REPO_ROOT}/charts/platform-${svc}"
  tmp="$(mktemp -d)"
  git -C "${PLATFORM_REPO}" archive "${tag}" "${src}" | tar -x -C "${tmp}"
  mkdir -p "${dest}"
  keep="${dest}/values-onprem.yaml"
  [[ -f "${keep}" ]] && cp "${keep}" "${tmp}/values-onprem.yaml.keep"
  find "${dest}" -mindepth 1 -maxdepth 1 ! -name values-onprem.yaml -exec rm -rf {} +
  cp -R "${tmp}/${src}/." "${dest}/"
  rm -rf "${dest}/values"
  python3 - "${dest}/Chart.yaml" "${svc}" "${chart_version}" "${tag}" <<'PY'
import re, sys
p, svc, ver, tag = sys.argv[1:]
s = open(p).read()
s = re.sub(r"(?m)^name:.*$", f"name: platform-{svc}", s, count=1)
s = re.sub(r"(?m)^version:.*$", f'version: "{ver}"', s, count=1)
s = re.sub(r"(?m)^appVersion:.*\n", "", s)
s = re.sub(r"(?m)^(version:.*)$", rf'\1\nappVersion: "{tag}"', s, count=1)
open(p, "w").write(s)
PY
  rm -rf "${tmp}"
  # On-prem patch: grid's migrations as Replicated* tables when ClickHouse is replicas + Keeper (off by default).
  if [[ "${svc}" == "grid" ]]; then
    python3 "${REPO_ROOT}/scripts/patch-platform-grid-replicated.py" "${dest}"
  fi
  # Keep the image-mirror tags (charts/straiker-artifact) in step with the chart's release.
  for repo in "${svc}" "${svc}-migrations"; do
    REPO="straiker/${repo}" NEWTAG="${tag}" perl -0777 -pi -e \
      's/(source:[ \t]*\S*\/\Q$ENV{REPO}\E[ \t]*\n[ \t]*tag:[ \t]*)\S+/${1}$ENV{NEWTAG}/' \
      "${REPO_ROOT}/charts/straiker-artifact/values.yaml"
  done
  echo "synced ${svc} @ ${tag} -> charts/platform-${svc} (chart ${chart_version})"
done

# ClickHouse CDC target DDL for charts/straiker-ch-sync (see doc/clickhouse-ingestion-design.md).
ddl_out="${REPO_ROOT}/charts/straiker-ch-sync/files/cdc_targets.sql"
mkdir -p "$(dirname "${ddl_out}")"
git -C "${PLATFORM_REPO}" show "${tag}:services/grid/deploy/harness/seed/cdc_snapshot.sql" | python3 -c '
import re, sys
src = sys.stdin.read()
src = re.sub(r"(?m)--[^\n]*$", "", src)          # drop comments (none inside string literals in the CREATE TABLEs)
stmts = [m.group(0).strip() + ";" for m in re.finditer(r"CREATE TABLE IF NOT EXISTS grid\.[^;]*", src)]
print("-- Generated by scripts/sync-platform-charts.sh from grid deploy/harness/seed/cdc_snapshot.sql; do not edit.")
print("CREATE DATABASE IF NOT EXISTS grid;\n")
print("\n\n".join(stmts))
' > "${ddl_out}"
echo "wrote ${ddl_out} ($(grep -c 'CREATE TABLE' "${ddl_out}") tables, from ${tag})"
